/**
 * The `/su` command list as the SRD's `/discord` page documents it, read from
 * the registered builder (`suCommand.data`) so the page cannot fall behind the
 * bot: a subcommand added, renamed or re-described here is on the page after
 * `bun run gen:command-list`, and `commandList.test.ts` fails until it is.
 *
 * The rendered module is committed at `apps/srd/src/generated/discordCommands.ts`;
 * the srd imports it as data, never the bot itself.
 */

import { suCommand } from './commands/su'

/** Discord's option type for a subcommand and for a subcommand group. */
const SUBCOMMAND = 1
const SUBCOMMAND_GROUP = 2

/**
 * The subcommands that answer with no In the Union now account: the reference
 * tools. Everything else reads or writes a Game, so a new subcommand is listed
 * as needing an account until it is named here.
 */
const NO_ACCOUNT = new Set(['roll', 'lookup', 'screen'])

type CommandOption = { name: string; required: boolean }

export type CommandListEntry = {
  /** The subcommand's path under `/su`: `roll`, or `game bind` in a group. */
  name: string
  description: string
  options: CommandOption[]
  /** Whether it answers without an In the Union now account. */
  needsAccount: boolean
}

type OptionJson = {
  type: number
  name: string
  description: string
  required?: boolean
  options?: OptionJson[]
}

function entry(prefix: string, sub: OptionJson): CommandListEntry {
  return {
    name: `${prefix}${sub.name}`,
    description: sub.description,
    options: (sub.options ?? []).map((option) => ({
      name: option.name,
      required: option.required === true,
    })),
    needsAccount: prefix !== '' || !NO_ACCOUNT.has(sub.name),
  }
}

/** Every leaf subcommand of `/su`, in registration order; a group's leaves under its name. */
export function commandList(
  options: OptionJson[] = suCommand.data.toJSON().options as OptionJson[]
): CommandListEntry[] {
  return options.flatMap((option) => {
    if (option.type === SUBCOMMAND) return [entry('', option)]
    if (option.type === SUBCOMMAND_GROUP) {
      return (option.options ?? []).map((leaf) => entry(`${option.name} `, leaf))
    }
    return []
  })
}

/** The committed module the srd imports: the list as typed data. */
export function renderCommandListModule(entries: CommandListEntry[] = commandList()): string {
  return `// GENERATED by apps/discord-bot/src/gen-command-list.ts — DO NOT EDIT BY HAND.
// Regenerate with: bun --filter discord-bot gen:command-list
//
// Every /su subcommand, read from the bot's registered builder, for the
// /discord page. apps/discord-bot/src/__tests__/commandList.test.ts fails if
// this file goes stale.

export type DiscordCommand = {
  name: string
  description: string
  options: readonly { name: string; required: boolean }[]
  needsAccount: boolean
}

export const DISCORD_COMMANDS: readonly DiscordCommand[] = ${JSON.stringify(entries, null, 2)}
`
}
