import { buildLookupMessage } from './commands/lookup'
import { buildRollMessage } from './commands/roll'
import type { ButtonSpec, ContainerBlock, ContainerData } from './container'
import { entityFromKey } from './lookupCard'

/**
 * The replies the reference site's `/discord` page shows as its screenshots (owner,
 * 2026-10-20: "generate the discord screenshots"): a `/su roll` and a
 * `/su lookup`, built by the very builders the bot answers with, a fixed die
 * and a fixed entry so the page does not change between builds. Written by
 * `gen-sample-replies.ts`; `__tests__/sampleReplies.test.ts` fails if the
 * committed copy goes stale.
 */

/** Who the sample roll names as its roller. */
const ROLLER = 'Scrapper'

/** The sample roll's die: a Core Mechanic success. */
const DIE = 17

/** The sample lookup's entry, the page's own first lookup example. */
const LOOKUP = 'systems::green-laser'

export type SampleReply = {
  /** The command as typed. */
  command: string
  data: ContainerData
}

export function sampleReplies(): { roll: SampleReply; lookup: SampleReply } {
  const roll = buildRollMessage('Core Mechanic', ROLLER, () => DIE)
  if ('error' in roll) throw new Error(roll.error)
  const hit = entityFromKey(LOOKUP)
  if (!hit) throw new Error(`sample lookup missing: ${LOOKUP}`)
  return {
    roll: { command: '/su roll', data: roll.data },
    lookup: {
      command: `/su lookup entity: ${hit.entity.name.toLowerCase()}`,
      data: buildLookupMessage(hit).data,
    },
  }
}

/** A button as a picture draws it: what it says, never what it calls. */
function pictured(
  button: ButtonSpec
): ButtonSpec | Omit<Extract<ButtonSpec, { kind: 'action' }>, 'customId'> {
  if (button.kind === 'link') return button
  const { customId: _, ...shown } = button
  return shown
}

/** A block as a picture draws it: its controls' ids and a menu's options dropped. */
function picturedBlock(block: ContainerBlock): unknown {
  if (block.kind === 'buttons') return { ...block, buttons: block.buttons.map(pictured) }
  if (block.kind === 'select') return { kind: 'select', placeholder: block.placeholder }
  if (block.kind === 'section' && block.button) return { ...block, button: pictured(block.button) }
  return block
}

/** A reply as the page draws it. */
function picturedReply({ command, data }: SampleReply) {
  return { command, data: { accent: data.accent, blocks: data.blocks.map(picturedBlock) } }
}

export function renderSampleRepliesModule(): string {
  return `// Generated by apps/discord-bot/src/gen-sample-replies.ts: do not edit by hand.
// Regenerate with: bun --filter discord-bot gen:sample-replies
//
// A /su roll and a /su lookup reply, built by the bot's own builders, for the
// /discord page's screenshots. apps/discord-bot/src/__tests__/sampleReplies.test.ts
// fails if this file goes stale.

export type SampleButton =
  | { kind: 'action'; label: string; style?: number; disabled?: boolean }
  | { kind: 'link'; url: string; label: string }

export type SampleBlock =
  | { kind: 'text'; content: string }
  | { kind: 'separator' }
  | { kind: 'section'; text: string[]; thumbnail?: { url: string; description?: string }; button?: SampleButton }
  | { kind: 'buttons'; buttons: SampleButton[] }
  | { kind: 'select'; placeholder: string }

export type SampleReply = { command: string; data: { accent: number; blocks: SampleBlock[] } }

export const DISCORD_SAMPLES: { roll: SampleReply; lookup: SampleReply } = ${JSON.stringify(
    (({ roll, lookup }) => ({ roll: picturedReply(roll), lookup: picturedReply(lookup) }))(
      sampleReplies()
    ),
    null,
    2
  )}
`
}
